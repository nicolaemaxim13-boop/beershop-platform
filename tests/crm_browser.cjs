// Run against an isolated, empty local DB with a deterministic FX stub.
const {chromium} = require('../frontend/node_modules/playwright');
const assert = require('node:assert/strict');
const baseURL = process.env.CRM_TEST_URL || 'http://127.0.0.1:8018';
const token = process.env.CRM_TEST_TOKEN || 't'.repeat(40);
const origin = new URL(baseURL);
assert(['127.0.0.1','localhost'].includes(origin.hostname), 'Only a local test server is allowed');

(async()=>{
 const browser = await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH ? {executablePath:process.env.CHROMIUM_PATH} : {}),args:['--no-sandbox']});
 try {
  const context = await browser.newContext({baseURL,viewport:{width:1366,height:900}});
  await context.route('**/*',route=>new URL(route.request().url()).origin===origin.origin?route.continue():route.abort());
  const page = await context.newPage(), errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const auth = {Authorization:'Bearer '+token};
  const request = async(method,path,data)=>{
   const result = await context.request.fetch(path,{method,headers:auth,data});
   assert(result.ok(),path+': '+await result.text());return result.json();
  };
  const stamp=Date.now(), email=`crm-${stamp}@example.test`;
  const categories=await request('GET','/api/categories');
  const product=await request('POST','/api/admin/products',{name:'Тестовий пивний кран',slug:'crm-browser-'+stamp,category_id:categories[0].id,image_url:'/assets/crm-icons/store.svg'});
  const variant=await request('POST',`/api/admin/products/${product.id}/variants`,{sku:'CRM-'+stamp,price:'250.00',stock:10,currency:'UAH'});
  await page.goto('/');
  await page.locator('#cards .card').first().waitFor();
  await page.locator('#search').fill('Тестовий пивний кран');
  await page.locator(`button[onclick="add(${product.id})"]`).click();
  await page.locator('header button').click();
  await page.locator('#checkout [name=name]').fill('Тестовий покупець');
  await page.locator('#checkout [name=phone]').fill('+380501234567');
  await page.locator('#checkout [name=email]').fill(email);
  await page.locator('#checkout [name=delivery_address]').fill('Тестове місто, відділення 1');
  const created=page.waitForResponse(r=>r.url().endsWith('/api/orders')&&r.request().method()==='POST');
  await page.locator('#orderbtn').click();
  const checkout=await created.catch(async error=>{
   await page.screenshot({path:'/tmp/crm-checkout-failure.png',fullPage:true});
   console.error('Checkout diagnostic:',await page.locator('#message').textContent(),errors);
   throw error;
  });assert.equal(checkout.status(),201);
  const placed=await checkout.json();
  const reserved=await request('GET','/api/admin/inventory/'+variant.id);
  assert.deepEqual([reserved.available,reserved.reserved,reserved.on_hand],[9,1,10]);
  await page.goto('/crm');
  await page.locator('#admin-token').fill(token);
  await page.getByRole('button',{name:'Увійти',exact:true}).click();
  await page.locator('#workspace').waitFor({state:'visible'});
  await page.locator('#loading').waitFor({state:'hidden'});
  await page.locator('[data-view="managers"]').click();
  await page.locator('#create').click();
  await page.locator('#manager-name').fill('Тестовий менеджер '+stamp);
  await page.locator('#save-edit').click();
  await page.locator('#editor').waitFor({state:'hidden'});
  await page.locator('[data-view="orders"]').click();
  assert(await page.locator('#create').isHidden());
  await page.locator(`#list [data-action="order"][data-id="${placed.id}"]`).click();
  await page.locator('#detail').waitFor({state:'visible'});
  await page.locator('#assignment-form').waitFor();
  const invoice=await page.locator('#detail-title').textContent();
  assert.match(invoice,/BS-\d+/);
  assert(await page.locator('[data-status="fulfilled"]').isDisabled());
  await page.locator('#assigned').selectOption({label:'Тестовий менеджер '+stamp});
  await page.locator('#priority').selectOption('high');
  await page.locator('#assignment-form button').click();
  await page.waitForFunction(()=>document.querySelector('#notice')?.textContent==='Зміни збережено');
  assert.equal(await page.locator('#notice').evaluate(el=>el.parentElement.id),'detail');
  await page.locator('#note-text').fill('<img src=x onerror=alert(1)> Тестова нотатка');
  await page.locator('#note-form button').click();
  await page.getByText('<img src=x onerror=alert(1)> Тестова нотатка',{exact:true}).waitFor();
  assert.equal(await page.locator('.note img').count(),0);
  await page.locator('[data-status="confirmed"]').click();
  await page.waitForFunction(()=>document.querySelector('[data-status="confirmed"]')?.disabled);
  await page.locator('[data-action="bank"]').click();
  await page.locator('#bank-tx').fill('LOCAL-FIXTURE-'+stamp);
  await page.locator('#bank-amount').fill('1.00');
  await page.locator('#bank-ref').fill('Оплата '+invoice);
  await page.locator('#editor input[type=checkbox]').check();
  await page.locator('#save-edit').click();
  await page.locator('#editor-error').waitFor({state:'visible'});
  await page.locator('#bank-amount').fill('250.00');
  await page.locator('#save-edit').click();
  await page.locator('#editor').waitFor({state:'hidden'});
  assert(await page.locator('[data-status="fulfilled"]').isDisabled());
  assert(await page.locator('[data-status="cancelled"]').isDisabled());
  await page.locator('[data-status="picking"]').click();
  await page.waitForFunction(()=>document.querySelector('#detail .badge.picking'));
  await page.locator('[data-action="waybill"]').click();
  await page.locator('#waybill').fill('2'+String(stamp).padStart(13,'0'));
  await page.locator('#editor input[type=checkbox]').check();
  await page.locator('#save-edit').click();
  await page.locator('#editor').waitFor({state:'hidden'});
  for(const status of ['handed_over','delivered']){
   await page.locator('[data-action="delivery-manual"]').click();
   assert.equal(await page.locator('#delivery-state').inputValue(),status);
   await page.locator('#editor input[type=checkbox]').check();
   await page.locator('#save-edit').click();
   await page.locator('#editor').waitFor({state:'hidden'});
  }
  await page.locator('[data-status="fulfilled"]').click();
  await page.waitForFunction(()=>document.querySelector('#detail .badge.fulfilled'));
  assert.equal(await page.locator('#assigned option:checked').textContent(),'Тестовий менеджер '+stamp);
  const shipped=await request('GET','/api/admin/inventory/'+variant.id);
  assert.deepEqual([shipped.available,shipped.reserved,shipped.on_hand],[9,0,9]);
  await page.screenshot({path:'/tmp/crm-order-desktop.png',fullPage:true});
  await page.locator('#detail [data-action="customer"]').click();
  await page.locator('[data-action="edit-customer"]').click();
  await page.locator('#contact-name').fill('Тестовий клієнт з оновленим іменем');
  await page.locator('#save-edit').click();
  await page.locator('#editor').waitFor({state:'hidden'});
  await page.waitForFunction(()=>document.querySelector('#detail-title')?.textContent==='Тестовий клієнт з оновленим іменем');
  assert.equal(await page.locator('#detail-title').textContent(),'Тестовий клієнт з оновленим іменем');
  await page.locator('[data-close="detail"]').click();
  await page.locator('#query').fill(email);
  await page.locator('#query').press('Enter');
  await page.waitForFunction(()=>document.querySelector('#result-count').textContent==='Знайдено: 1');
  await page.screenshot({path:'/tmp/crm-desktop.png',fullPage:true});
  for(const width of [390,320]){
   await page.setViewportSize({width,height:844});
   assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Page overflow at '+width);
   await page.locator('#list [data-action="order"]').click();
   await page.locator('#detail').waitFor({state:'visible'});
   assert(await page.locator('#detail').evaluate(el=>el.scrollWidth<=el.clientWidth),'Drawer overflow at '+width);
   if(width===390)await page.screenshot({path:'/tmp/crm-mobile.png',fullPage:true});
   await page.locator('[data-close="detail"]').click();
  }
  await page.locator('[data-view="customers"]').click();
  await page.locator('#query').fill(email);await page.locator('#query').press('Enter');
  await page.waitForFunction(()=>document.querySelector('#result-count').textContent==='Знайдено: 1');
  await page.locator('#list [data-action="customer"]').click();
  assert.equal(await page.locator('[data-action="new-customer-order"]').count(),0);
  await page.locator('[data-close="detail"]').click();
  await page.locator('[data-view="inventory"]').click();
  await page.locator('#query').fill('CRM-'+stamp);await page.locator('#query').press('Enter');
  await page.locator(`#list [data-action="stock"][data-id="${variant.id}"]`).click();
  await page.locator('[data-action="edit-stock"]').click();
  await page.locator('#stock-on-hand').fill('12');
  await page.locator('#stock-reason').fill('Тестовий акт перерахунку');
  assert(await page.locator('#editor').evaluate(el=>el.scrollWidth<=el.clientWidth),'Mobile editor overflow');
  await page.screenshot({path:'/tmp/inventory-mobile-editor.png',fullPage:true});
  await page.locator('#save-edit').click();await page.locator('#editor').waitFor({state:'hidden'});
  const corrected=await request('GET','/api/admin/inventory/'+variant.id);
  assert.deepEqual([corrected.available,corrected.reserved,corrected.on_hand],[12,0,12]);
  await page.screenshot({path:'/tmp/inventory-mobile-detail.png',fullPage:true});
  await page.locator('[data-close="detail"]').click();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'/tmp/inventory-mobile.png',fullPage:true});
  await page.setViewportSize({width:1366,height:900});
  await page.screenshot({path:'/tmp/inventory-desktop.png',fullPage:true});
  await page.locator('#logout').click();
  assert.equal(await page.locator('#list').textContent(),'');
  assert(await page.evaluate(()=>!localStorage.length&&!sessionStorage.length));
  assert.deepEqual(errors,[]);
  console.log('CRM browser workflows passed: storefront checkout -> automatic CRM/reserve -> picking -> local delivery -> stock write-off -> fulfillment; corrections, contacts, mobile/desktop, no manual CRM orders.');
 } finally {await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1});
